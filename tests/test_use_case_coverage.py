"""Варіанти використання, які лишалися без жодної перевірки.

Зіставлення варіантів використання з ендпоінтами й тестами (таблиця в
розділі 4 записки) показало три ендпоінти, яких не викликав жоден тест:
показники DORA, попередній перегляд плану для коміту й запуск перенавчання.
Усі три працювали, але стверджувати «перевірено» про них було нічим.
"""
from __future__ import annotations

import pytest
from fastapi.testclient import TestClient
from sqlalchemy import select

from app.api import models_api
from app.db import SessionLocal
from app.main import app
from app.models import CIProvider, Commit, Pipeline, Project

API = "/api/v1"


@pytest.fixture(scope="module")
def client() -> TestClient:
    return TestClient(app)


def _token(client: TestClient, email: str, password: str) -> dict:
    r = client.post(f"{API}/auth/login", json={"email": email, "password": password})
    assert r.status_code == 200, r.text
    return {"Authorization": f"Bearer {r.json()['access_token']}"}


@pytest.fixture(scope="module")
def devops(client: TestClient) -> dict:
    return _token(client, "devops@example.com", "devops123")


@pytest.fixture(scope="module")
def developer(client: TestClient) -> dict:
    return _token(client, "dev@example.com", "dev123")


@pytest.fixture(scope="module")
def lead(client: TestClient) -> dict:
    return _token(client, "lead@example.com", "lead123")


@pytest.fixture(scope="module")
def project() -> Project:
    db = SessionLocal()
    try:
        p = db.scalars(select(Project).where(Project.ci_provider == CIProvider.SYNTHETIC)).first()
        assert p is not None, "потрібен синтетичний стенд: scripts/seed_synthetic.py"
        db.expunge(p)
        return p
    finally:
        db.close()


def test_lead_sees_the_four_dora_metrics(client: TestClient, lead: dict, project: Project):
    """ВВ-8: чотири показники DORA за обраний період."""
    r = client.get(f"{API}/projects/{project.id}/dora", headers=lead, params={"days": 365})
    assert r.status_code == 200, r.text
    dora = r.json()
    assert dora["deployments"] > 0, "за рік на основній гілці мають бути успішні прогони"
    assert dora["deployment_frequency_per_day"] == pytest.approx(dora["deployments"] / 365, abs=0.001)
    assert 0 <= dora["change_failure_rate"] <= 1
    assert dora["lead_time_hours"] >= 0 and dora["time_to_restore_hours"] >= 0


def test_developer_previews_the_risk_for_a_commit(client: TestClient, developer: dict, project: Project):
    """ВВ-10: прогноз ризику збою для конкретної зміни, без запуску конвеєра."""
    db = SessionLocal()
    try:
        sha = db.scalar(
            select(Pipeline.commit_sha).where(Pipeline.project_id == project.id)
            .order_by(Pipeline.started_at.desc())
        )
    finally:
        db.close()
    r = client.get(f"{API}/pipelines/plan/preview/{project.id}/{sha}", headers=developer)
    assert r.status_code == 200, r.text
    plan = r.json()["plan"]
    assert 0 <= plan["risk"] <= 1
    assert plan["mode"] in ("skip", "full", "sharded", "selective")
    assert plan["rationale"], "план без пояснення розробникові нічого не каже"
    assert r.json()["gitlab_yaml"].startswith("# Generated by")

    missing = client.get(f"{API}/pipelines/plan/preview/{project.id}/{'0' * 40}", headers=developer)
    assert missing.status_code == 404


def test_only_devops_starts_retraining(
    client: TestClient, devops: dict, developer: dict, project: Project,
    monkeypatch: pytest.MonkeyPatch,
):
    """ВВ-23: перенавчання запускається у фоні й лише DevOps-інженером.

    Саме навчання тут підмінено: воно триває хвилини й створило б у реєстрі
    стенда нові версії моделей. Його поведінку перевіряє test_retrain_guard.
    """
    started: list[tuple[int, str]] = []
    monkeypatch.setattr(models_api, "_retrain", lambda pid, branch: started.append((pid, branch)))

    denied = client.post(f"{API}/projects/{project.id}/models/retrain", headers=developer)
    assert denied.status_code == 403 and not started

    r = client.post(f"{API}/projects/{project.id}/models/retrain", headers=devops)
    assert r.status_code == 202 and r.json()["accepted"] is True
    assert started == [(project.id, project.default_branch)]
