"""Плагін, який виконується всередині чужого конвеєра.

Це єдиний компонент системи, що працює на боці користувача, і найризикованіший:
якщо він упаде або поверне сміття, зламається чужий конвеєр. Тому перевіряється
головне - він НІКОЛИ не завершується помилкою і завжди лишає придатний опис
конвеєра.

Окремо перевіряється те, що легко переплутати: повний набір тестів буває з двох
різних причин. Або система недоступна - це аварія, яку треба помітити. Або
система доступна й свідомо повернула повний набір, бо проєкт ще не в бойовому
режимі. Плагін колись писав в обох випадках «система оптимізації недоступна»,
через що інженер шукав би проблему, якої немає.
"""
from __future__ import annotations

import importlib.util
import json
import subprocess
import sys
from pathlib import Path

import pytest
import yaml

ROOT = Path(__file__).resolve().parents[1]
PLUGIN = ROOT / "cli" / "cicd_opt.py"


def load_plugin():
    spec = importlib.util.spec_from_file_location("cicd_opt", PLUGIN)
    mod = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(mod)
    return mod


@pytest.fixture(scope="module")
def plugin():
    return load_plugin()


@pytest.fixture()
def repo(tmp_path: Path) -> Path:
    """Маленький репозиторій: плагін читає зміни через git."""
    def git(*a):
        subprocess.run(["git", *a], cwd=tmp_path, check=True,
                       capture_output=True, text=True)

    git("init", "-q", ".")
    git("config", "user.email", "t@example.com")
    git("config", "user.name", "tester")
    src = tmp_path / "src" / "auth"
    src.mkdir(parents=True)
    (src / "a.py").write_text("x = 1\n")
    git("add", "-A")
    git("commit", "-qm", "base")
    (src / "a.py").write_text("x = 2\n")
    git("commit", "-qam", "change auth")
    return tmp_path


def run_plugin(repo: Path, api: str, out: str = "pipeline.yml", extra: list[str] | None = None):
    sha = subprocess.run(["git", "rev-parse", "HEAD"], cwd=repo,
                         capture_output=True, text=True, check=True).stdout.strip()
    cmd = [
        sys.executable, str(PLUGIN), "plan",
        "--api", api, "--project", "1",
        "--ref", "feature/check", "--sha", sha, "--base", "HEAD~1",
        "--output", out, "--timeout", "3",
        *(extra or []),
    ]
    return subprocess.run(cmd, cwd=repo, capture_output=True, text=True), sha


# ------------------------------------------------- головний запобіжник
def test_plugin_never_fails_the_pipeline_when_the_optimiser_is_down(repo: Path):
    """Недоступність системи не має валити чужий конвеєр."""
    proc, _ = run_plugin(repo, "http://127.0.0.1:9/api/v1")
    assert proc.returncode == 0, proc.stderr
    assert (repo / "pipeline.yml").exists()


def test_fallback_yaml_is_a_valid_full_run(repo: Path):
    run_plugin(repo, "http://127.0.0.1:9/api/v1")
    doc = yaml.safe_load((repo / "pipeline.yml").read_text())
    assert doc["stages"], "у запасному плані немає стадій"
    jobs = [k for k in doc if k != "stages"]
    assert jobs, "у запасному плані немає задач"
    for j in jobs:
        assert "script" in doc[j], f"задача {j} без script не виконається"


def test_outage_is_reported_as_an_outage(repo: Path):
    """Причина в самому файлі: її побачить той, хто відкриє артефакт."""
    proc, _ = run_plugin(repo, "http://127.0.0.1:9/api/v1")
    head = (repo / "pipeline.yml").read_text().splitlines()[0].lower()
    assert "unreachable" in head or "fallback" in head
    assert "unavailable" in proc.stdout.lower() or "unreachable" in proc.stdout.lower()


# ---------------------------------------- свідомий повний набір проти аварії
def test_deliberate_full_run_is_not_reported_as_an_outage(plugin):
    """Найважливіша відмінність: план порахований, але не застосований.

    Це нормальний стан упровадження, а не збій. Якби тут писалося про
    недоступність, кожен прогін у режимі холостого ходу виглядав би як аварія.
    """
    text = plugin.full_run_yaml("Plan computed but not applied: project is in «dry_run» mode")
    low = text.lower()
    assert "not applied" in low
    assert "unreachable" not in low and "unavailable" not in low

    doc = yaml.safe_load(text)
    assert doc["stages"] and [k for k in doc if k != "stages"]


def test_outage_reason_is_carried_into_the_file(plugin):
    text = plugin.full_run_yaml("Fallback: the optimiser was unreachable (timeout)")
    assert "unreachable" in text.lower()
    assert yaml.safe_load(text)["stages"]


# --------------------------------------------------------- розбір відповіді
def test_applied_plan_is_written_as_is(plugin, repo: Path, monkeypatch):
    """Коли план застосовується, у файл має потрапити саме він, а не заглушка."""
    child = (
        "# Generated by Slipstream\n"
        "stages:\n  - test\n\n"
        "test:shard-1:\n  stage: test\n  script:\n    - pytest --test-ids \"1,2\"\n"
    )
    plan = {
        "mode": "selective", "risk": 0.31, "risk_threshold": 0.45,
        "selected_tests": 40, "total_tests": 120, "shards": 2,
        "est_duration_s": 120.0, "baseline_duration_s": 300.0, "saving_ratio": 0.6,
        "rationale": ["predicted failure risk 31%"], "fallbacks": [],
        "applied": True,
    }

    class Resp:
        def __init__(self, payload=None, text=""):
            self._payload, self.text = payload, text

        def raise_for_status(self):
            return None

        def json(self):
            return self._payload

    class Client:
        def __init__(self, *a, **k):
            pass

        def __enter__(self):
            return self

        def __exit__(self, *a):
            return False

        def post(self, url, json=None, **k):
            return Resp(plan) if (json or {}).get("format") != "gitlab-yaml" else Resp(text=child)

    monkeypatch.setattr(plugin.httpx, "Client", Client)
    monkeypatch.chdir(repo)          # плагін читає зміни через git у поточному каталозі
    sha = subprocess.run(["git", "rev-parse", "HEAD"], cwd=repo,
                         capture_output=True, text=True, check=True).stdout.strip()
    out = repo / "applied.yml"
    rc = plugin.main([
        "plan", "--api", "http://stub", "--project", "1",
        "--ref", "feature/check", "--sha", sha, "--base", "HEAD~1",
        "--output", str(out), "--json-output", str(repo / "plan.json"),
    ])
    assert rc == 0
    assert "test:shard-1" in out.read_text(), "застосований план підмінено заглушкою"
    assert json.loads((repo / "plan.json").read_text())["selected_tests"] == 40
