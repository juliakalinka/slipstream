# Перевірка вважається живою, якщо виконувалася хоча б раз за стільки останніх
# прогонів. Значення підібрано на даних RTPTorrent: scripts/tune_active_window.py,
# результат у results/active_window_tuning.txt.
ACTIVE_WINDOW_BUILDS = int(os.getenv("CICD_ACTIVE_WINDOW_BUILDS", "30"))


@dataclass
class PlannedJob:
    name: str
    stage: str
    order: int
    test_ids: list[int] = field(default_factory=list)
    # посилання у форматі pytest «шлях::ім'я»: за ними задачу можна виконати
    test_refs: list[str] = field(default_factory=list)
    est_duration_s: float = 0.0
    shard_index: int | None = None
    shard_total: int | None = None


@dataclass
class PipelinePlan:
    project_id: int
    commit_sha: str
    ref: str
    mode: str                       # skip | full | sharded | selective
    jobs: list[PlannedJob]
    risk: float
    risk_threshold: float
    selected_tests: int
    total_tests: int
    est_duration_s: float
    baseline_duration_s: float
    shards: int
    rationale: list[str]
    fallbacks: list[str]
    model_versions: dict[str, str]
    generated_at: datetime

    @property
    def saved_s(self) -> float:
        return max(0.0, self.baseline_duration_s - self.est_duration_s)

    @property
    def saving_ratio(self) -> float:
        return self.saved_s / self.baseline_duration_s if self.baseline_duration_s else 0.0

    def to_dict(self) -> dict:
        return {
            "project_id": self.project_id,
            "commit_sha": self.commit_sha,
            "ref": self.ref,
            "mode": self.mode,
            "risk": round(self.risk, 4),
            "risk_threshold": self.risk_threshold,
            "selected_tests": self.selected_tests,
            "total_tests": self.total_tests,
            "shards": self.shards,
            "est_duration_s": round(self.est_duration_s, 1),
            "baseline_duration_s": round(self.baseline_duration_s, 1),
            "saved_s": round(self.saved_s, 1),
            "saving_ratio": round(self.saving_ratio, 4),
            "rationale": self.rationale,
            "fallbacks": self.fallbacks,
            "model_versions": self.model_versions,
            "generated_at": self.generated_at.isoformat(),
            "jobs": [
                {
                    "name": j.name, "stage": j.stage, "order": j.order,
                    "tests": len(j.test_ids), "est_duration_s": round(j.est_duration_s, 1),
                    "shard": f"{j.shard_index + 1}/{j.shard_total}" if j.shard_index is not None else None,
                }
                for j in self.jobs
            ],
        }

    def to_gitlab_yaml(self) -> str:
        """Опис дочірнього конвеєра GitLab CI, який повертається задачі «plan»."""
        lines = [
            "# Generated by Slipstream - CI/CD pipeline intelligence",
            f"# commit {self.commit_sha[:10]}  branch {self.ref}  mode {self.mode}",
            f"# failure risk {self.risk:.2f}; selected {self.selected_tests} of {self.total_tests} tests",
            f"# estimated {self.est_duration_s / 60:.1f} min instead of {self.baseline_duration_s / 60:.1f} min",
            "",
            "stages:",
        ]
        stages: list[str] = []
        for j in self.jobs:
            if j.stage not in stages:
                stages.append(j.stage)
        lines += [f"  - {s}" for s in stages]
        lines.append("")

        for j in self.jobs:
            lines.append(f"{j.name}:")
            lines.append(f"  stage: {j.stage}")
            if j.test_ids:
                lines.append("  script:")
                if j.test_refs:
                    # посилання pytest: такий опис виконується як є
                    refs = " ".join(f'"{r}"' for r in j.test_refs)
                    lines.append(f"    - pytest --junitxml=junit-{j.name.replace(':', '-')}.xml {refs}")
                else:
                    # шляхи перевірок ще невідомі: виконується весь набір
                    ids = ",".join(str(t) for t in j.test_ids)
                    lines.append(f'    - echo "selected test ids: {ids}"')
                    lines.append("    - pytest --junitxml=junit-all.xml")
                # Звіт JUnit надсилає сама задача: він утворюється в дочірньому
                # конвеєрі, і батьківський його не бачить.
                lines.append("  after_script:")
                lines.append('    - >')
                lines.append('      if [ -n "$CICD_OPT_API" ] && [ -n "$CICD_OPT_SECRET" ]; then')
                lines.append(f'      for f in junit-{j.name.replace(":", "-")}*.xml; do')
                lines.append('      [ -f "$f" ] || continue;')
                lines.append('      curl --silent --show-error --retry 2 -X POST')
                lines.append('      -H "X-CICD-Token: $CICD_OPT_SECRET"')
                lines.append('      -H "Content-Type: application/xml"')
                lines.append('      --data-binary "@$f"')
                lines.append('      "$CICD_OPT_API/webhooks/junit/$CICD_OPT_PROJECT?external_id=$CI_PIPELINE_ID&commit_sha=$CI_COMMIT_SHA&ref=$CI_COMMIT_REF_NAME"')
                lines.append('      || echo "report failed for $f"; done; fi')
                lines.append("  artifacts:")
                lines.append("    when: always")
                lines.append("    paths: [\"junit-*.xml\"]")
                lines.append("    reports:")
                lines.append("      junit: \"junit-*.xml\"")
                lines.append("  variables:")
                lines.append(f'    SELECTED_TESTS: "{len(j.test_ids)}"')
                if j.shard_index is not None:
                    lines.append(f'    SHARD: "{j.shard_index + 1}/{j.shard_total}"')
            else:
                lines.append("  script:")
                lines.append(f'    - make {j.name.replace(":", "-")}')
            lines.append(f"  # predicted duration {j.est_duration_s:.0f}s")
            lines.append("")
        return "\n".join(lines)


def _load_test_stats(
    db: Session, project_id: int, cutoff: datetime | None = None
) -> tuple[list[TestStats], SuiteStats]:
    """Зібрати історію перевірок і наборів для моделі ранжування."""
    cases = db.scalars(select(TestCase).where(TestCase.project_id == project_id)).all()
    stats = {
        c.id: TestStats(
            test_id=c.id, suite=c.suite, name=c.name, file_path=c.file_path,
            avg_duration_ms=c.avg_duration_ms or 1000.0, runs=c.total_runs,
            failures=c.total_failures, flaky_score=c.flaky_score,
            last_failed_at=c.last_failed_at, quarantined=c.quarantined,
            order_dependent=bool(getattr(c, "order_dependent", False)),
        )
        for c in cases
    }

    # Кандидати - лише живі перевірки. Таблиця test_cases зберігає всі, які
    # проєкт колись мав; видалені й перейменовані забирали б бюджет часу.
    recent_q = (
        select(Pipeline.id)
        .where(Pipeline.project_id == project_id)
        .order_by(Pipeline.started_at.desc())
        .limit(ACTIVE_WINDOW_BUILDS)
    )
    if cutoff is not None:
        recent_q = recent_q.where(Pipeline.started_at < cutoff)
    recent_ids = list(db.scalars(recent_q))
    if recent_ids:
        alive = set(db.scalars(
            select(TestResult.test_case_id)
            .join(Job, TestResult.job_id == Job.id)
            .where(Job.pipeline_id.in_(recent_ids))
            .distinct()
        ))
        # порожнє вікно не має лишити план без перевірок
        if alive:
            stats = {k: v for k, v in stats.items() if k in alive}

    # Підсумкові поля test_cases враховують усю історію. Під час відтворення
    # минулого вони містили б майбутнє відносно cutoff і завищували б якість,
    # тому тут рахуються заново на обрізаній історії.
    if cutoff is not None:
        agg = db.execute(
            select(
                TestResult.test_case_id,
                func.count(TestResult.id),
                func.sum(case((TestResult.status == TestStatus.FAILED, 1), else_=0)),
                func.max(case((TestResult.status == TestStatus.FAILED, Pipeline.started_at))),
            )
            .join(Job, TestResult.job_id == Job.id)
            .join(Pipeline, Job.pipeline_id == Pipeline.id)
            .where(Pipeline.project_id == project_id)
            .where(Pipeline.started_at < cutoff)
            .group_by(TestResult.test_case_id)
        ).all()
        past = {row[0]: row for row in agg}
        for st in stats.values():
            row = past.get(st.test_id)
            if row is None:
                st.runs = st.failures = 0
                st.last_failed_at = None
            else:
                st.runs = int(row[1] or 0)
                st.failures = int(row[2] or 0)
                lf = row[3]
                if isinstance(lf, str):
                    try:
                        lf = datetime.fromisoformat(lf)
                    except ValueError:
                        lf = None
                st.last_failed_at = lf
            # оцінка нестабільності теж рахується за всією історією: обнуляється
            st.flaky_score = 0.0

    # зміни в яких модулях супроводжували падіння кожної перевірки й набору
    rows = db.execute(
        select(TestResult.test_case_id, Commit.changed_paths)
        .join(Job, TestResult.job_id == Job.id)
        .join(Pipeline, Job.pipeline_id == Pipeline.id)
        .join(Commit, Pipeline.commit_sha == Commit.sha)
        .where(Pipeline.project_id == project_id)
        .where(TestResult.status == TestStatus.FAILED)
        .where(Pipeline.started_at < cutoff if cutoff is not None else True)
    ).all()

    suite_stats = SuiteStats()
    for tc_id, paths in rows:
        st = stats.get(tc_id)
        if st is None:
            continue
        mods = {module_of(p) for p in (paths or [])}
        for m in mods:
            st.module_failures[m] = st.module_failures.get(m, 0) + 1
        suite_stats.observe(st.suite, mods, True)

    # кількість запусків кожного набору: для частоти падінь
    for st in stats.values():
        suite_stats.runs[st.suite] = suite_stats.runs.get(st.suite, 0) + st.runs
    return list(stats.values()), suite_stats


def _test_ref(t) -> str:
    """Посилання pytest «шлях::ім'я»; порожнє, якщо шлях перевірки невідомий."""
    if t is None or not getattr(t, "file_path", ""):
        return ""
    return f"{t.file_path}::{t.name}"


def build_plan(
    db: Session,
    project: Project,
    commit: Commit,
    ref: str | None = None,
    force_mode: str | None = None,
    cutoff: datetime | None = None,
) -> PipelinePlan:
    """Сформувати план конвеєра для коміту.

    cutoff - момент, на який відтворюється історія: під час експерименту план
    будується так, ніби пізніших прогонів ще не було.
    """
    ref = ref or commit.branch or project.default_branch
    policy: ResolvedPolicy = resolve_policy(db, project, ref)
    rationale: list[str] = []
    fallbacks: list[str] = []
    model_versions: dict[str, str] = {}
    now = datetime.now(timezone.utc)

    # Крок 4 (множина кандидатів) виконує _load_test_stats. Перелік потрібен
    # уже тут: за ним рахується базова тривалість.
    all_tests, suite_stats = _load_test_stats(db, project.id, cutoff)
    total_tests = len(all_tests)
    baseline_test_s = sum(t.avg_duration_ms for t in all_tests) / 1000.0

    # тривалість задач, які виконуються завжди
    job_hist = job_duration_history(db, project.id, cutoff)
    dur_mv = registry.active(db, project.id, ModelType.DURATION)
    dur_est = None
    if dur_mv:
        dur_est, _ = registry.load(dur_mv)
        model_versions["duration"] = dur_mv.version

    def est_job(name: str, stage: str) -> float:
        h = job_hist.get(name, [])
        if dur_est is not None:
            f = build_job_features(name, stage, 0, commit, job_hist,
                                   cache_hit=True, is_sharded=False)
            vector = [f[k] for k in DURATION_FEATURES]
            return duration_model.predict(dur_est, vector)
        return sum(h) / len(h) if h else 60.0

    build_s = est_job("build", "build")
    lint_s = est_job("lint", "lint")
    baseline_total = build_s + lint_s + baseline_test_s

    # Крок 1. Класифікація зміни: якщо змінено лише документацію, конвеєр
    # пропускається (за політикою лишається тільки lint).
    paths = commit.changed_paths or []
    kinds = [classify_path(p) for p in paths]
    docs_only = bool(paths) and all(k == "docs" for k in kinds)

    if force_mode == "full":
        fallbacks.append("mode forced to full run")
    elif project.plan_mode == PlanMode.OFF:
        fallbacks.append(
            "project is in observe-only mode, optimisation is disabled"
        )
    elif docs_only and policy.skip_docs_only:
        jobs = []
        if policy.keep_lint_on_skip:
            jobs.append(PlannedJob("lint", "lint", 0, est_duration_s=lint_s))
        rationale.append(
            f"all {len(paths)} changed files are documentation, no testing needed"
        )
        return PipelinePlan(
            project_id=project.id, commit_sha=commit.sha, ref=ref, mode="skip",
            jobs=jobs, risk=0.0, risk_threshold=policy.risk_threshold,
            selected_tests=0, total_tests=total_tests,
            est_duration_s=sum(j.est_duration_s for j in jobs),
            baseline_duration_s=baseline_total, shards=0, rationale=rationale,
            fallbacks=fallbacks, model_versions=model_versions, generated_at=now,
        )

    # Крок 2. Оцінювання ризику збою. Без навченої моделі оцінка нейтральна.
    risk = 0.5
    fail_mv = registry.active(db, project.id, ModelType.FAILURE)
    if fail_mv:
        est, feat_names = registry.load(fail_mv)
        hist = load_history(db, project.id, cutoff)
        feats = build_commit_features(commit, ref, hist, project.default_branch)
        risk = failure_model.predict(est, features_to_vector(feats, feat_names))
        model_versions["failure"] = fail_mv.version
        rationale.append(f"predicted failure risk {risk:.0%}")
    else:
        fallbacks.append("risk model is not trained yet, using a neutral estimate")

    # Крок 3. Запобіжники: кожен із них повертає повний набір перевірок.
    pipelines_count = len(db.scalars(
        select(Pipeline.id).where(Pipeline.project_id == project.id)
    ).all())

    use_selection = policy.test_selection
    if not use_selection:
        fallbacks.append(
            f"test selection policy does not cover branch «{ref}»: "
            f"running the full suite"
        )
    on_default = ref == project.default_branch
    if use_selection and policy.protect_default_branch and on_default:
        use_selection = False
        fallbacks.append(
            "default branch is protected: running the full test suite"
        )
    if use_selection and pipelines_count < settings.min_pipelines_to_optimize:
        use_selection = False
        fallbacks.append(
            f"only {pipelines_count} pipeline runs collected out of "
            f"{settings.min_pipelines_to_optimize} required"
        )
    dry_run = project.plan_mode == PlanMode.DRY_RUN and force_mode != "optimized"
    if use_selection and dry_run:
        fallbacks.append(
            "dry run: the plan is computed but the full suite is executed"
        )
    if use_selection and risk >= 0.85:
        use_selection = False
        fallbacks.append("failure risk too high: running the full suite is safer")

    # Крок 5. Відбір перевірок під бюджет часу.
    rank_mv = registry.active(db, project.id, ModelType.TEST_RANK)
    ranker = TestRanker()
    if rank_mv:
        est, names = registry.load(rank_mv)
        ranker = TestRanker(est, names)
        model_versions["test_rank"] = rank_mv.version
    else:
        fallbacks.append(
            "test ranking model is not trained, falling back to the heuristic"
        )

    quarantined = [t for t in all_tests if t.quarantined]
    if quarantined and policy.flaky_quarantine:
        n_q = len(quarantined)
        rationale.append(
            f"{n_q} flaky test{'' if n_q == 1 else 's'} "
            f"{'is' if n_q == 1 else 'are'} quarantined"
        )

    if use_selection:
        # бюджет: суворіший із відносного й абсолютного; що вищий ризик,
        # то ширша перевірка
        budget = min(policy.budget_s, baseline_test_s * policy.budget_ratio)
        budget *= 1.0 + min(risk, 0.8)
        sel = select_tests(
            all_tests, paths, budget_s=budget, ranker=ranker,
            min_keep_ratio=policy.min_keep_ratio, now=now, suite_stats=suite_stats,
        )
        chosen_ids = set(sel.selected)
        test_scores = sel.scores
        rationale.append(sel.reason)
    else:
        chosen_ids = {
            t.test_id for t in all_tests
            if not (t.quarantined and policy.flaky_quarantine)
        }
        # повний набір теж упорядковується за ризиком, щоб падіння сталося раніше
        active = [t for t in all_tests if t.test_id in chosen_ids]
        feats = [build_rank_features(t, paths, now, suite_stats) for t in active]
        scores = ranker.score_many(feats)
        test_scores = dict(zip((t.test_id for t in active), scores))
        rationale.append(
            f"running the full suite: {len(chosen_ids)} test"
            f"{'' if len(chosen_ids) == 1 else 's'}"
        )

    # Крок 6. Добір залежних від порядку. Якщо в плані є хоч одна така
    # перевірка, беруться всі залежні перевірки її набору: без тієї, що готує
    # стан, решта впаде не через дефект. Це стосується й перевірок у карантині.
    def _complete_order_dependent(ids: set[int]) -> None:
        suites = {
            t.suite for t in all_tests if t.order_dependent and t.test_id in ids
        }
        if not suites:
            return
        added = 0
        for t in all_tests:
            if t.order_dependent and t.suite in suites and t.test_id not in ids:
                ids.add(t.test_id)
                added += 1
        if added:
            rationale.append(
                f"added {added} order-dependent test{'' if added == 1 else 's'} "
                f"to keep suite{'' if len(suites) == 1 else 's'} "
                f"{', '.join(sorted(suites))} intact"
            )

    _complete_order_dependent(chosen_ids)
    chosen = [t for t in all_tests if t.test_id in chosen_ids]

    # Крок 7. Розподіл між виконавцями.
    def _shard(tests: list[TestStats]) -> tuple[int, ShardingResult | None]:
        total_s = sum(t.avg_duration_ms / 1000.0 for t in tests)
        k = 1
        if policy.sharding and tests:
            need = suggest_shard_count(
                total_s, policy.target_shard_s, policy.max_shards
            )
            k = min(policy.max_shards, need)
        # залежні від порядку перевірки одного набору йдуть неподільною групою,
        # решта - кожна окремо
        groups: dict[str, tuple[list[int], float]] = {}
        for t in tests:
            key = f"suite:{t.suite}" if t.order_dependent else f"test:{t.test_id}"
            ids, acc = groups.get(key, ([], 0.0))
            ids.append(t.test_id)
            groups[key] = (ids, acc + t.avg_duration_ms / 1000.0)
        return k, (lpt_shard_groups(groups, k) if tests else None)

    shards, sh = _shard(chosen)

    # Крок 8. Доцільність відбору. Відбір і розподіл скорочують той самий
    # критичний шлях, а пропустити дефект може лише відбір. Якщо поверх
    # розподілу він дає менше заданої частки, виконується повний набір.
    if use_selection and len(chosen) < total_tests:
        full = [
            t for t in all_tests if not (t.quarantined and policy.flaky_quarantine)
        ]
        k_full, sh_full = _shard(full)
        base = sh_full.makespan_s if sh_full else 0.0
        gain = (base - sh.makespan_s) / base if base > 0 and sh else 0.0
        if gain < policy.min_selection_gain:
            rationale.append(
                f"test selection would shorten the critical path "
                f"by only {gain:.0%} on top of {k_full} shards: "
                f"running the full suite instead"
            )
            chosen_ids = {t.test_id for t in full}
            _complete_order_dependent(chosen_ids)
            chosen = [t for t in all_tests if t.test_id in chosen_ids]
            shards, sh = _shard(chosen)
            use_selection = False

    od_test_ids = {t.test_id for t in chosen if t.order_dependent}
    if od_test_ids:
        n_od = len(od_test_ids)
        rationale.append(
            f"{n_od} test{'' if n_od == 1 else 's'} "
            f"{'is' if n_od == 1 else 'are'} order dependent: "
            f"neither reordered nor split across shards"
        )

    # Крок 9. Упорядкування задач: за високого ризику швидка задача йде першою.
    first = [("build", build_s), ("lint", lint_s)]
    if policy.fail_fast and risk >= policy.risk_threshold:
        first.reverse()
        rationale.append("risk above threshold: fast checks run first")
    jobs = [
        PlannedJob(name, name, i, est_duration_s=est)
        for i, (name, est) in enumerate(first)
    ]
    order = len(jobs)

    by_id = {t.test_id: t for t in chosen}
    if sh is not None:
        for shard in sh.shards:
            if not shard.test_ids:
                continue
            # у межах виконавця перевірки йдуть за спаданням оцінки ризику;
            # залежні від порядку зберігають свій порядок і йдуть блоком у кінці
            od_ids = [t for t in shard.test_ids if t in od_test_ids]
            free_ids = [t for t in shard.test_ids if t not in od_test_ids]
            ordered_ids = sorted(
                free_ids, key=lambda t: test_scores.get(t, 0.0), reverse=True
            ) + sorted(od_ids)
            refs = [_test_ref(by_id.get(t)) for t in ordered_ids]
            jobs.append(PlannedJob(
                name=f"test:shard-{shard.index + 1}", stage="test", order=order,
                test_ids=ordered_ids, test_refs=[r for r in refs if r],
                est_duration_s=shard.est_duration_s,
                shard_index=shard.index, shard_total=shards,
            ))
            order += 1
        rationale.append(
            f"{len(chosen)} tests spread over {shards} shards, "
            f"critical path {sh.makespan_s:.0f}s instead of {sh.sequential_s:.0f}s"
        )

    est_total = build_s + lint_s + (sh.makespan_s if sh else 0.0)
    if use_selection and len(chosen) < total_tests:
        mode = "selective"   # відібрано частину перевірок
    elif shards > 1:
        mode = "sharded"     # повний набір, розподілений між виконавцями
    else:
        mode = "full"

    return PipelinePlan(
        project_id=project.id, commit_sha=commit.sha, ref=ref, mode=mode, jobs=jobs,
        risk=risk, risk_threshold=policy.risk_threshold, selected_tests=len(chosen),
        total_tests=total_tests, est_duration_s=est_total,
        baseline_duration_s=baseline_total, shards=shards, rationale=rationale,
        fallbacks=fallbacks, model_versions=model_versions, generated_at=now,
    )
