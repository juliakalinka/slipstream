"""Формування оптимізованого плану конвеєра.

Кроки: класифікація зміни, оцінювання ризику, перевірка запобіжників,
визначення множини кандидатів, відбір перевірок, добір залежних від порядку,
розподіл між виконавцями, перевірка доцільності відбору, упорядкування задач.
"""
